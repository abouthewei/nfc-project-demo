const languageButtons = document.querySelectorAll(".lang-switch");
function setLanguage(language) {
  const selected = language === "en" ? "en" : "zh";
  const words = copy[selected];
  document.documentElement.lang = selected === "zh" ? "zh-CN" : "en";
  document.body.classList.toggle("lang-en", selected === "en");
  document.querySelectorAll("[data-i18n]").forEach(function (element) {
    const key = element.dataset.i18n;
    if (words[key] !== undefined) element.textContent = words[key];
  });
  document.querySelectorAll("[data-i18n-html]").forEach(function (element) {
    const key = element.dataset.i18nHtml;
    if (words[key] !== undefined) element.innerHTML = words[key];
  });
  document.querySelectorAll("[data-i18n-svg]").forEach(function (element) {
    const key = element.dataset.i18nSvg;
    if (words[key] !== undefined) element.textContent = words[key];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(function (element) {
    const key = element.dataset.i18nAria;
    if (words[key] !== undefined) element.setAttribute("aria-label", words[key]);
  });
  document.querySelectorAll("[data-alt-zh][data-alt-en]").forEach(function (image) {
    image.alt = selected === "zh" ? image.dataset.altZh : image.dataset.altEn;
  });
  languageButtons.forEach(function (button) {
    button.innerHTML = selected === "zh" ? '中文 <span aria-hidden="true">/</span> English' : '中文 <span aria-hidden="true">/</span> EN';
    button.setAttribute("aria-label", selected === "zh" ? "Switch to English" : "切换至中文");
  });
  const title = document.querySelector("[data-page-title-" + selected + "]");
  if (title) document.title = title.dataset["pageTitle" + (selected === "zh" ? "Zh" : "En")];
  else document.title = selected === "zh" ? "南风古灶 · 一座仍在生活的陶城" : "Nanfeng Kiln · A Living Pottery Town";
  try { localStorage.setItem("nanfeng-lang", selected); } catch (error) { /* Language still works when storage is unavailable. */ }
}

let initialLanguage = "zh";
try {
  const savedLanguage = localStorage.getItem("nanfeng-lang");
  if (savedLanguage === "zh" || savedLanguage === "en") initialLanguage = savedLanguage;
} catch (error) { /* Chinese is the default when storage is unavailable. */ }
setLanguage(initialLanguage);
languageButtons.forEach(function (button) {
  button.addEventListener("click", function () {
    setLanguage(document.documentElement.lang === "zh-CN" ? "en" : "zh");
  });
});

function activateView() {
  const requested = window.location.hash.replace(/^#/, "") || "top";
  const viewName = requested === "history" ? "history" : (requested === "craft" || requested === "craft-process" ? "craft" : "home");
  document.querySelectorAll("section[data-view]").forEach(function (view) {
    const active = view.dataset.view === viewName;
    view.hidden = !active;
    view.setAttribute("aria-hidden", active ? "false" : "true");
  });
  if (viewName === "home" && (requested === "route" || requested === "visit")) {
    document.getElementById("route").scrollIntoView({block: "start"});
  } else if (viewName === "home" || viewName === "history" || viewName === "craft") {
    window.scrollTo(0, 0);
  }
}
window.addEventListener("hashchange", activateView);
activateView();

